export const getLevelColor = (level) => {
  if (!level) return LEVEL_COLORS.Alle;
  const upper = String(level).trim().toUpperCase();
  if (LEVEL_COLORS[upper]) return LEVEL_COLORS[upper];
  if (upper.includes('B2')) return LEVEL_COLORS.B2;
  if (upper.includes('B1')) return LEVEL_COLORS.B1;
  if (upper.includes('A2')) return LEVEL_COLORS.A2;
  if (upper.includes('A1')) return LEVEL_COLORS.A1;
  if (upper.includes('C2')) return LEVEL_COLORS.C2;
  if (upper.includes('C1')) return LEVEL_COLORS.C1;
  return LEVEL_COLORS[level] || LEVEL_COLORS.Alle;
};
